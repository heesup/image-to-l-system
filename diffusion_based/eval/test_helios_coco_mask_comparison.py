"""
Leaf Mask Comparison Script comparing Helios C++ COCO Ground-Truth Leaf Mask against PyTorch Organ Array Render Mask.
Reads exact COCO polygon annotations from `plot_0000_masks.json` generated by Helios C++ (`./main --renderer radiation`).
Calculates exact Leaf Mask IoU, Dice coefficient, and saves visual comparison figure to `diffusion_based/eval/output/helios_coco_mask_comparison.png`.
"""

import os
import json
import argparse
import numpy as np
import torch
from PIL import Image, ImageDraw
import matplotlib.pyplot as plt

from diffusion_based.models.plant_organ_array import PlantOrganArray
from diffusion_based.models.helios_pytorch_geometry import HeliosPlantGeometryBuilder
from diffusion_based.models.helios_pytorch_renderer import HeliosPyTorchRenderer


def decode_helios_coco_leaf_mask(json_path: str) -> np.ndarray:
    """Decodes ground truth leaf mask from Helios C++ COCO JSON output."""
    with open(json_path, 'r') as f:
        data = json.load(f)

    img_info = data['images'][0]
    W, H = img_info['width'], img_info['height']
    helios_leaf_mask = np.zeros((H, W), dtype=bool)

    for ann in data['annotations']:
        if ann['category_id'] == 2: # Category 2 = Leaf
            seg = ann['segmentation']
            for poly in seg:
                img = Image.new('L', (W, H), 0)
                ImageDraw.Draw(img).polygon(poly, outline=1, fill=1)
                helios_leaf_mask |= np.array(img, dtype=bool)

    return helios_leaf_mask


def evaluate_coco_leaf_mask_comparison(
    xml_path: str,
    json_path: str,
    rad_img_path: str,
    output_dir: str = "diffusion_based/eval/output",
    use_generic_leaves: bool = True
):
    os.makedirs(output_dir, exist_ok=True)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

    print(f"Loading Organ Array Tensor from {xml_path}...")
    organ_array = PlantOrganArray.from_xml_file(xml_path)

    print("Decoding Helios C++ Ground Truth Leaf Mask from COCO JSON...")
    helios_gt_mask = decode_helios_coco_leaf_mask(json_path) # (720, 720)
    H, W = helios_gt_mask.shape

    print(f"Rendering PyTorch Organ Array at resolution {W}x{H} (Generic Leaves: {use_generic_leaves}, Device: {device})...")
    builder = HeliosPlantGeometryBuilder(use_generic_leaves=use_generic_leaves, leaf_scale_factor=1.0, tube_radial_subdivisions=6)
    renderer = HeliosPyTorchRenderer(image_size=W)
    renderer.geo_builder = builder

    pytorch_render_t = renderer.render_organ_array(
        organ_array, azimuth_deg=0.0, elevation_deg=90.0, camera_height=5.0, background="ground", device=device
    )

    pytorch_rgb = pytorch_render_t.permute(1, 2, 0).cpu().numpy()

    # Exact organ-type leaf mask from the PyTorch rasterizer (organ 2 = leaf)
    mesh_dict = renderer.geo_builder.build_mesh_from_organ_array(organ_array, device=device)
    organ_type_buffer = renderer.render_organ_type_buffer(
        mesh_dict, azimuth_deg=0.0, elevation_deg=90.0, camera_height=5.0, focus_plant=True
    )
    pytorch_leaf_mask = (organ_type_buffer == 2).cpu().numpy()

    # Metrics
    intersection = (pytorch_leaf_mask & helios_gt_mask).sum()
    union = (pytorch_leaf_mask | helios_gt_mask).sum()
    iou = float(intersection / union) if union > 0 else 1.0
    dice = float(2 * intersection / (pytorch_leaf_mask.sum() + helios_gt_mask.sum())) if (pytorch_leaf_mask.sum() + helios_gt_mask.sum()) > 0 else 1.0

    print("\n" + "=" * 60)
    print("   HELIOS C++ RADIATION GROUND TRUTH VS PYTORCH LEAF MASK   ")
    print("=" * 60)
    print(f"  Helios C++ GT Leaf Pixel Count : {helios_gt_mask.sum()}")
    print(f"  PyTorch Render Leaf Pixel Count: {pytorch_leaf_mask.sum()}")
    print(f"  Leaf Mask IoU                  : {iou:.4f}")
    print(f"  Leaf Mask Dice Coefficient     : {dice:.4f}")
    print("=" * 60 + "\n")

    # Load Helios Radiation RGB Image
    rad_rgb = np.array(Image.open(rad_img_path).convert("RGB"), dtype=np.float32) / 255.0

    # Side-by-Side Visual Plot (5 columns)
    fig, axes = plt.subplots(1, 5, figsize=(22, 4.5))

    axes[0].imshow(rad_rgb)
    axes[0].set_title("Helios C++ Ray-Traced (Radiation)")
    axes[0].axis("off")

    axes[1].imshow(pytorch_rgb)
    axes[1].set_title(f"PyTorch Organ Array (Generic: {use_generic_leaves})")
    axes[1].axis("off")

    axes[2].imshow(helios_gt_mask, cmap="gray")
    axes[2].set_title("Helios GT Leaf Mask")
    axes[2].axis("off")

    axes[3].imshow(pytorch_leaf_mask, cmap="gray")
    axes[3].set_title("PyTorch Leaf Mask")
    axes[3].axis("off")

    mask_comp = np.zeros((H, W, 3))
    mask_comp[helios_gt_mask, 0] = 1.0      # Red = Helios GT
    mask_comp[pytorch_leaf_mask, 1] = 1.0   # Green = PyTorch Render
    axes[4].imshow(mask_comp)
    axes[4].set_title(f"Mask Overlay (IoU={iou:.3f}, Dice={dice:.3f})")
    axes[4].axis("off")

    plt.tight_layout()
    save_path = os.path.join(output_dir, "helios_coco_mask_comparison.png")
    plt.savefig(save_path, dpi=150)
    plt.close()

    print(f"Saved Helios COCO leaf mask comparison figure to: {save_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--xml",
        default="Digital-Crops/projects/syntheticdata_generation/build/output_rad_test/plot_0000_plant_0000.xml"
    )
    parser.add_argument(
        "--json",
        default="Digital-Crops/projects/syntheticdata_generation/build/output_rad_test/plot_0000_masks.json"
    )
    parser.add_argument(
        "--rad-img",
        default="Digital-Crops/projects/syntheticdata_generation/build/output_rad_test/plot_0000_rad.jpeg"
    )
    parser.add_argument("--output-dir", default="diffusion_based/eval/output")
    parser.add_argument("--generic-leaves", action="store_true", default=False)
    args = parser.parse_args()

    evaluate_coco_leaf_mask_comparison(args.xml, args.json, args.rad_img, args.output_dir, use_generic_leaves=args.generic_leaves)
